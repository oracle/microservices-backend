#!/usr/bin/env bash
set -euo pipefail
set +x
readonly SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export PORT="${PORT:-8085}"
export AZN_ISSUER_URI="${AZN_ISSUER_URI:-http://127.0.0.1:8080}"
export AZN_JWK_SET_URI="${AZN_JWK_SET_URI:-$AZN_ISSUER_URI/oauth2/jwks}"
export AZN_AUDIENCE="${AZN_AUDIENCE:-cloudbank-api}"
export AI_AGENT_CALLER_CLIENT_IDS="${AI_AGENT_CALLER_CLIENT_IDS:-cloudbank-service-client}"
export AI_AGENT_TOKEN_URI="${AI_AGENT_TOKEN_URI:-$AZN_ISSUER_URI/oauth2/token}"
export AI_AGENT_CLIENT_ID="${AI_AGENT_CLIENT_ID:-cloudbank-ai-agent-client}"
export AI_DATASOURCE_PASSWORD="${AI_DATASOURCE_PASSWORD:?Set AI_DATASOURCE_PASSWORD for CB_AI_AGENT_APP}"
export DOCUMENT_INGEST_BASE_URL="${DOCUMENT_INGEST_BASE_URL:-http://127.0.0.1:8082}"
export AI_AGENT_CLIENT_SECRET="${AI_AGENT_CLIENT_SECRET:?Set AI_AGENT_CLIENT_SECRET}"
export DOCUMENT_REVIEW_BASE_URL="${DOCUMENT_REVIEW_BASE_URL:-http://127.0.0.1:8084}"
export AI_OCI_GENAI_AUTHENTICATION_TYPE="${AI_OCI_GENAI_AUTHENTICATION_TYPE:-WORKLOAD_IDENTITY}"
export AI_OCI_GENAI_REGION="${AI_OCI_GENAI_REGION:?Set AI_OCI_GENAI_REGION}"
export AI_OCI_GENAI_CHAT_MODEL="${AI_OCI_GENAI_CHAT_MODEL:?Set AI_OCI_GENAI_CHAT_MODEL}"
export OKE_CLUSTER_COMPARTMENT_ID="${OKE_CLUSTER_COMPARTMENT_ID:?Set OKE_CLUSTER_COMPARTMENT_ID}"
export SPRING_MAIN_LAZY_INITIALIZATION="${SPRING_MAIN_LAZY_INITIALIZATION:-true}"
[[ "$AI_OCI_GENAI_AUTHENTICATION_TYPE" == WORKLOAD_IDENTITY ]] || {
    printf 'AI_OCI_GENAI_AUTHENTICATION_TYPE must be WORKLOAD_IDENTITY.\n' >&2
    exit 2
}
cd "$SCRIPT_DIR"
exec mvn spring-boot:run
