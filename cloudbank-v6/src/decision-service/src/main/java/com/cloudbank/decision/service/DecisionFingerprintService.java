package com.cloudbank.decision.service;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import org.springframework.stereotype.Component;

@Component
public class DecisionFingerprintService {
    public String sha256(String value) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256")
                    .digest(value.getBytes(StandardCharsets.UTF_8)));
        } catch (NoSuchAlgorithmException exception) {
            throw new IllegalStateException("SHA-256 is unavailable", exception);
        }
    }

    public String decisionId(String applicationId, String decisionType, String idempotencyKey) {
        return "DEC-" + sha256(applicationId + ":" + decisionType + ":" + idempotencyKey).substring(0, 32);
    }
}
