export DOCUMENT_INGEST_BASE_URL="${DOCUMENT_INGEST_BASE_URL:-http://127.0.0.1:8082}"
[[ -n "${DOCUMENT_REVIEW_DATASOURCE_PASSWORD:-}" && -n "${DOCUMENT_REVIEW_CLIENT_SECRET:-}" ]] || { printf 'Set DOCUMENT_REVIEW_DATASOURCE_PASSWORD and DOCUMENT_REVIEW_CLIENT_SECRET.\n' >&2; exit 2; }
cd "$SCRIPT_DIR"
exec mvn spring-boot:run
