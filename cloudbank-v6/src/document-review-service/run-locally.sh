set -euo pipefail
set +x
readonly SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export PORT="${PORT:-8084}"
export DOCUMENT_REVIEW_DATASOURCE_URL="${DOCUMENT_REVIEW_DATASOURCE_URL:-jdbc:oracle:thin:@//localhost:1521/freepdb1}"
export DOCUMENT_REVIEW_DATASOURCE_USERNAME="${DOCUMENT_REVIEW_DATASOURCE_USERNAME:-CB_DOCUMENT_REVIEW_APP}"
export DOCUMENT_REVIEW_SCHEMA="${DOCUMENT_REVIEW_SCHEMA:-CLOUDBANK}"
export AZN_ISSUER_URI="${AZN_ISSUER_URI:-http://127.0.0.1:8080}"
export AZN_JWK_SET_URI="${AZN_JWK_SET_URI:-$AZN_ISSUER_URI/oauth2/jwks}"
export DOCUMENT_REVIEW_TOKEN_URI="${DOCUMENT_REVIEW_TOKEN_URI:-$AZN_ISSUER_URI/oauth2/token}"
export DOCUMENT_REVIEW_CLIENT_ID="${DOCUMENT_REVIEW_CLIENT_ID:-cloudbank-document-review-client}"
export DOCUMENT_REVIEW_CALLER_CLIENT_IDS="${DOCUMENT_REVIEW_CALLER_CLIENT_IDS:-cloudbank-service-client}"
