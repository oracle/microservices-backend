package com.cloudbank.documentreview.service;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import org.springframework.stereotype.Service;

@Service
public class ReviewFingerprintService {
    public String sha256(String value) {
        try {
            return HexFormat.of()
                    .formatHex(MessageDigest.getInstance("SHA-256").digest(value.getBytes(StandardCharsets.UTF_8)));
        } catch (NoSuchAlgorithmException exception) {
            throw new IllegalStateException("SHA-256 is unavailable", exception);
        }
    }

    public String reviewId(String applicationId, String profileVersion, String idempotencyKey) {
        return "DREV-" + sha256(applicationId + ":" + profileVersion + ":" + idempotencyKey).substring(0, 32);
    }
}
